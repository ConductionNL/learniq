// A user on the Dutch locale reads learniq in Dutch: every English string of
// the catalogue has a Dutch value, in the server catalogue (nl.json) and the
// browser catalogue (nl.js) alike; every schema name of the register
// is in the catalogue with a Dutch name; and every notification rule of the register carries an
// `nl` subject, which OpenRegister sends to a user whose language is Dutch.
//
// Run via `node --test tests/unit-js/` (package.json `test:js-unit`).
//
// @spec openspec/changes/capability-rows-say-what-they-do/specs/i18n-locale-parity/spec.md#requirement-a-user-on-the-dutch-locale-reads-the-screens-and-notifications-in-dutch

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { test } from 'node:test'

const root = new URL('../../', import.meta.url)

/**
 * A JSON file of the app.
 *
 * @param {string} path The path from the app root.
 * @return {object} The parsed file.
 */
function json(path) {
	return JSON.parse(readFileSync(new URL(path, root), 'utf8'))
}

/**
 * The pairs an `OC.L10N.register(app, {...}, plural)` browser catalogue registers.
 *
 * @param {string} path The path from the app root.
 * @return {object} The translations.
 */
function browserCatalogue(path) {
	let registered = null
	const OC = { L10N: { register: (app, translations) => { registered = translations } } }
	// The catalogue is generated by scripts/build-l10n-js.js from the .json.
	new Function('OC', readFileSync(new URL(path, root), 'utf8'))(OC)
	return registered
}

/**
 * The English keys with no Dutch value.
 *
 * @param {object} english The English catalogue.
 * @param {object} dutch The Dutch catalogue.
 * @return {Array<string>} The keys without a Dutch value.
 */
function untranslated(english, dutch) {
	return Object.keys(english).filter((key) => {
		const value = dutch[key]
		if (Array.isArray(value)) return value.some((form) => String(form).trim() === '')
		return typeof value !== 'string' || value.trim() === ''
	})
}

test('Scenario "A Dutch teacher opens the app": every string of the server catalogue has a Dutch value', () => {
	const english = json('l10n/en.json').translations
	assert.ok(Object.keys(english).length > 1000, 'the English catalogue is read')
	assert.deepEqual(untranslated(english, json('l10n/nl.json').translations), [])
})

test('every string of the browser catalogue has a Dutch value, so the screens read in Dutch', () => {
	const english = browserCatalogue('l10n/en.js')
	assert.ok(Object.keys(english).length > 1000, 'the English browser catalogue is read')
	assert.deepEqual(untranslated(english, browserCatalogue('l10n/nl.js')), [])
})

test('every schema name of the register is in the catalogue and has a Dutch name for its forms', () => {
	const english = json('l10n/en.json').translations
	const dutch = json('l10n/nl.json').translations
	const schemas = Object.values(json('lib/Settings/learniq_register.json').components.schemas)
	const titles = schemas.map((schema) => schema.title).filter((title) => typeof title === 'string' && title !== '')
	assert.ok(titles.length > 150, 'the register\'s schema names are read')
	// A title missing from the English catalogue is a key no translation is looked up for.
	assert.deepEqual(titles.filter((title) => !(title in english)), [])
	assert.deepEqual(titles.filter((title) => typeof dutch[title] !== 'string' || dutch[title].trim() === ''), [])
})

test('Scenario "A Dutch parent gets a notification": every notification rule carries an nl subject', () => {
	const schemas = json('lib/Settings/learniq_register.json').components.schemas
	const rules = Object.entries(schemas).flatMap(([name, schema]) =>
		Object.entries(schema['x-openregister-notifications'] ?? {}).map(([id, rule]) => ({ name, id, rule })),
	)
	assert.ok(rules.length > 50, 'the register\'s notification rules are read')
	const withoutDutch = rules
		.filter(({ rule }) => typeof rule.subject?.nl !== 'string' || rule.subject.nl.trim() === '')
		.map(({ name, id }) => `${name}.${id}`)
	assert.deepEqual(withoutDutch, [])
})

test('the parity baseline holds no Dutch gap, so a new English string without Dutch fails check:l10n', () => {
	const baseline = json('l10n/.l10n-parity-baseline.json')
	assert.ok(baseline.strict.includes('nl'))
	for (const [set, entry] of Object.entries(baseline.sets)) {
		assert.deepEqual(entry.strictGaps?.nl ?? [], [], `${set} records no Dutch gap`)
	}
})
